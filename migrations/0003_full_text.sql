-- 要約しか配信しないフィードの本文を、記事ページから取ってくる（M7）。
--
-- 先読みする画像が無ければ画像の先読みは効かない。要約しか配信しないフィードが
-- 現実に多く（テクノエッジは description 100 字ほどで、本文も画像も記事ページ側に
-- ある）、画像の先読みと全文取得は同じ「読む前に手元へ落としておく」仕事なので、
-- 切り離さずに一緒に扱う（docs/ROADMAP.md M7）。

-- 全文取得の対象にするか。**既定は 0 で、決めるのはユーザ。** 相手のサーバに
-- 記事の数だけ取りに行く動作なので、こちらが勝手に始めない
ALTER TABLE feeds ADD COLUMN full_text INTEGER NOT NULL DEFAULT 0;

-- 全文取得を勧めたかどうか。3 値を取る。
--   0 … まだ何も言っていない
--   1 … クロール時に「要約しか配信していない」と見えたので勧めている
--   2 … ユーザが決めた（入れたのであれ断ったのであれ、二度と勧めない）
--
-- 2 が要るのは、勧めを断った状態を覚えるため。0 に戻すと、次のクロールで
-- 同じ判定が出て勧めが復活する
ALTER TABLE feeds ADD COLUMN full_text_suggested INTEGER NOT NULL DEFAULT 0;

-- 記事ページのどこが本文かを指すセレクタ。フィードにつき 1 回だけ判定して残し、
-- 以降の記事はこれで引く（src/crawler/choose.ts）。NULL なら次の取得時に判定する。
-- サイトが作り替えられて引けなくなったら NULL に戻して判定し直す
ALTER TABLE feeds ADD COLUMN full_text_selector TEXT;

-- セレクタを誰が決めたか（ai / score）。AI が外したことを後から追えるように残す
ALTER TABLE feeds ADD COLUMN full_text_source TEXT;

-- 記事ページから取れた本文（サニタイズ済み HTML のみ。不変条件 4）。3 状態を取る。
--   NULL … まだ取りに行っていない
--   ''   … 取りに行ったが採らなかった（抽出がフィードの本文より短かった）
--   その他 … 記事ページから取れた本文
--
-- '' が要るのは、採らなかった記事を毎クロール取り直さないため。NULL のままにすると、
-- セレクタが外れているフィードで未読 10 件を 15 分ごとに取りに行き続けることになり、
-- 相手のサーバへの礼儀に反するうえ、全体の予算を食って他のフィードが埋まらない。
-- 本文の位置を判定し直したときは NULL に戻して、もう一度試させる。
--
-- **body を上書きしない。** フィードが配信した本文を残しておけば、抽出を仕損じた
-- フィードは full_text を 0 に戻せば元の要約に戻せる（そのとき full_body は消す）。
-- 読み出し側は COALESCE(NULLIF(full_body, ''), body) で 1 つの body として返すので、
-- クライアントからはどちらが入っているか見えない
ALTER TABLE entries ADD COLUMN full_body TEXT;

-- 全文をまだ取りに行っていない記事を引く（設定を入れた後の穴埋め）。
-- 部分索引なので、全文取得を使わない限り実体はほぼ空
CREATE INDEX idx_entries_missing_full_body ON entries (feed_id, id) WHERE full_body IS NULL;
